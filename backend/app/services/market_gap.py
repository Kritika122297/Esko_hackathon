"""Market Jump: what changes on a pack when it moves from one market to another.

Rows come from the rule-pack clauses of both markets, matched by the brief fields each clause requires, plus a
small file of market profiles (market_profiles.json) for how some elements are presented (units, nutrition
format, allergen style, language). Profile entries are hand-written drafts, marked unverified, and may only cite
clause ids that exist in the rule packs. Nothing here is generated by AI. A market with no rules loaded gets an
explicit 'no rules available' row instead of guesses.
"""

from __future__ import annotations

import json
from functools import lru_cache
from typing import Dict, List, Literal, Optional

from pydantic import BaseModel, Field

from app.services.catalog import NUTRIENTS, dv_key
from app.services.guidelines import (GUIDELINE_DIR, Clause, canonical_clause, category_labels, clauses_for,
                                     has_market_rules, load_standards)

Severity = Literal["none", "warn", "blocking"]
GENERAL_ONLY = {"retail", "industrial"}  # categories without their own rule packs

NUTRITION_FIELDS = {"calories", "serving_size", "servings_per_package", "guaranteed_analysis", "nutritional_adequacy",
                    *(n.key for n in NUTRIENTS), *(dv_key(n.key) for n in NUTRIENTS if n.daily_value)}

# element -> (label, fields its clauses require, strict). Strict elements are redone for the new market whenever
# the rules differ, because the presentation itself changes (units, panel, language); others are checked.
ELEMENTS: Dict[str, tuple] = {
    "identity": ("Name of the product", {"statement_of_identity", "product_name", "brand"}, False),
    "ingredients": ("Ingredient list", {"ingredients", "inci_ingredients", "active_ingredients", "excipients"}, False),
    "allergens": ("Allergen presentation", {"allergen_statement"}, True),
    "net_quantity": ("Net quantity and units", {"net_weight"}, True),
    "nutrition": ("Nutrition panel format", NUTRITION_FIELDS, True),
    "language": ("Language of the label", set(), True),
    "marks": ("Mandatory marks and symbols", {"veg_logo", "ce_marking", "hazard_pictograms", "signal_word", "pao_symbol", "udi"}, True),
    "operator": ("Producer or responsible operator", {"producer", "responsible_person", "licence_number"}, False),
    "dates": ("Batch and date marking", {"batch_lot", "expiry_date", "manufacture_date"}, False),
    "price_origin": ("Price and country of origin", {"mrp", "country_of_origin"}, False),
    "warnings": ("Warnings, directions and first aid",
                 {"warnings", "directions", "first_aid", "hazard_statements", "precautionary_statements", "strength",
                  "dosage_form", "target_species", "feed_type", "feeding_guidelines"}, False),
    "barcode": ("Barcode (GTIN)", {"barcode"}, False),
}


class Side(BaseModel):
    text: str
    clause_id: Optional[str] = None


class GapRow(BaseModel):
    element: str
    key: str
    current: Optional[Side] = None
    target: Optional[Side] = None
    severity: Severity
    action_needed: str
    verified: bool = Field(False, description="False while the wording rests on a draft rule pack or market profile")


class MarketGap(BaseModel):
    source_market: str
    target_market: str
    category: str
    rules_available: bool
    rows: List[GapRow]
    summary: Dict[str, int]
    note: str


@lru_cache(maxsize=1)
def _profiles() -> Dict[str, Dict[str, dict]]:
    """Market profiles with inheritance resolved and unknown clause ids removed."""
    raw = json.loads((GUIDELINE_DIR / "market_profiles.json").read_text(encoding="utf-8"))["markets"]
    known = {c.id for s in load_standards().values() for c in s.clauses}
    out: Dict[str, Dict[str, dict]] = {}
    for market, entry in raw.items():
        merged = dict(raw.get(entry.get("inherits"), {})) if entry.get("inherits") else {}
        merged.update({k: v for k, v in entry.items() if k != "inherits"})
        merged.pop("inherits", None)
        for v in merged.values():
            if v.get("clause_id") and canonical_clause(v["clause_id"]) not in known:
                v["clause_id"] = None  # a profile may not cite a clause the rule packs do not have
        out[market] = merged
    return out


def _profile(market: str, element: str, category: str) -> Optional[dict]:
    entry = _profiles().get(market, {}).get(element)
    if entry and ("*" in entry.get("categories", ["*"]) or category in entry.get("categories", [])):
        return entry
    return None


def _side(market: str, category: str, element: str, clauses: List[Clause]) -> Optional[Side]:
    fields = ELEMENTS[element][1]
    hits = [c for c in clauses if any(r.field in fields for r in c.requires)]
    hits.sort(key=lambda c: c.standard == "base")  # the market's own rule first, the general one last
    prof = _profile(market, element, category)
    if prof:
        return Side(text=prof["text"], clause_id=prof.get("clause_id") or (hits[0].id if hits else None))
    if hits:
        return Side(text=hits[0].text, clause_id=hits[0].id)
    return None


def _ids(market: str, category: str, element: str, clauses: List[Clause]) -> set:
    fields = ELEMENTS[element][1]
    return {c.id for c in clauses if any(r.field in fields for r in c.requires)}


def _end(text: str) -> str:
    return text.rstrip(" .") + "."


def market_gap(source: str, target: str, category: str) -> MarketGap:
    source, target, category = source.strip().upper(), target.strip().upper(), (category or "food").lower()
    general_only = category in GENERAL_ONLY
    src_clauses, tgt_clauses = clauses_for(source, category), clauses_for(target, category)
    rules = has_market_rules(target, category) or general_only
    rows: List[GapRow] = []

    if not has_market_rules(target, category) and not general_only:
        rows.append(GapRow(
            element="Market rules", key="rules", severity="warn",
            current=Side(text=f"{source} rules for {category_labels().get(category, category)}") if has_market_rules(source, category) else None,
            target=Side(text=f"No rules are loaded for {target}; only the general checks below run."),
            action_needed=f"Ask Legal for the {target} labelling requirements before the pack is adapted."))

    for key, (label, _fields, strict) in ELEMENTS.items():
        if general_only and key in ("allergens", "nutrition", "marks"):
            continue  # these come from category rules, which general-only categories do not have
        cur = _side(source, category, key, src_clauses)
        tgt = _side(target, category, key, tgt_clauses)
        if cur is None and tgt is None:
            continue
        same_rules = _ids(source, category, key, src_clauses) == _ids(target, category, key, tgt_clauses)
        if tgt and not cur:
            severity, action = "blocking", f"New for {target}: {_end(tgt.text)}"
        elif cur and not tgt:
            severity, action = "warn", (f"No {target} rule for this is loaded. Keep it unless Legal confirms it "
                                        "can go.")
        elif same_rules and cur.text == tgt.text:
            severity, action = "none", "No change: the same rule applies."
        elif strict:
            severity, action = "blocking", f"Redo for {target}: {_end(tgt.text)}"
        else:
            severity, action = "warn", f"Check the wording against the {target} rule: {_end(tgt.text)}"
        rows.append(GapRow(element=label, key=key, current=cur, target=tgt, severity=severity, action_needed=action))

    order = {"blocking": 0, "warn": 1, "none": 2}
    rows.sort(key=lambda r: order[r.severity])
    summary = {s: sum(1 for r in rows if r.severity == s) for s in ("blocking", "warn", "none")}
    return MarketGap(source_market=source, target_market=target, category=category, rules_available=rules, rows=rows,
                     summary=summary,
                     note="From the draft rule packs and market profiles, not yet checked against the official "
                          "texts. Confirm with Legal before relying on it.")
