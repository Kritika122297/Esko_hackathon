def _pdf_fonts() -> Tuple[str, str]:
    """A TrueType font with arrows and curly quotes when one is installed; Helvetica otherwise."""
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    candidates = [("C:/Windows/Fonts/segoeui.ttf", "C:/Windows/Fonts/segoeuib.ttf"),
                  ("C:/Windows/Fonts/arial.ttf", "C:/Windows/Fonts/arialbd.ttf"),
                  ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
                  ("/Library/Fonts/Arial Unicode.ttf", "/Library/Fonts/Arial Unicode.ttf")]
    for reg, bold in candidates:
        if Path(reg).exists() and Path(bold).exists():
            try:
                if "BF" not in pdfmetrics.getRegisteredFontNames():
                    pdfmetrics.registerFont(TTFont("BF", reg))
                    pdfmetrics.registerFont(TTFont("BF-Bold", bold))
                    from reportlab.pdfbase.pdfmetrics import registerFontFamily
                    registerFontFamily("BF", normal="BF", bold="BF-Bold", italic="BF", boldItalic="BF-Bold")
                return "BF", "BF-Bold"
            except Exception:  # a broken font file must not stop the export
                continue
    return "Helvetica", "Helvetica-Bold"


def export_pdf(brief: DesignerBrief, path: Path) -> Path:
    from xml.sax.saxutils import escape

    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import (CondPageBreak, KeepTogether, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table,
                                    TableStyle)

    font, bold = _pdf_fonts()
    plain_font = font == "Helvetica"

    def X(text: str) -> str:
        t = _xml_safe(text)
        if plain_font:  # Helvetica has no arrows or curly quotes
            t = t.replace("→", "->").replace("“", '"').replace("”", '"').replace("’", "'").replace("…", "...")
        return escape(t)

    def col(h):
        return colors.HexColor("#" + h)

    def S(name, size=9, colour="ink2", leading=None, fnt=None, **kw):
        return ParagraphStyle(name, fontName=fnt or font, fontSize=size, leading=leading or size * 1.32,
                              textColor=col(C[colour]), **kw)

    body = S("body", 9.5)
    body_ink = S("bodyi", 9.5, "ink")
    small = S("small", 8.2)
    sub = S("sub", 7.8, "muted")
    note = S("note", 8.5, "muted")
    h1 = S("h1", 14, "ink", fnt=bold, spaceBefore=10, spaceAfter=2)
    h2 = S("h2", 11, "ink", fnt=bold, spaceBefore=8, spaceAfter=3)
    lead = S("lead", 8.8, "muted", spaceAfter=5)
    head = S("head", 6.8, "muted", fnt=bold)

    def tag_markup(t: Tag, size=7) -> str:
        bg, fg = TONES.get(t.tone, TONES["soft"])
        return f'<font name="{bold}" size="{size}" color="#{fg}" backColor="#{bg}">&nbsp;{X(t.text.upper())}&nbsp;</font>'

    def cell_flow(value: CellLike, small_table: bool):
        st = small if small_table else body
        if isinstance(value, Tag):
            return Paragraph(tag_markup(value), st)
        c = value if isinstance(value, Cell) else Cell(str(value))
        text = f'<font name="{bold}" color="#{C["ink"]}">{X(c.text)}</font>' if c.bold else X(c.text)
        if c.tag:
            text += "&nbsp;&nbsp;" + tag_markup(c.tag, 6.2)
        parts = [Paragraph(text, st)]
        if c.sub:
            parts.append(Paragraph(X(c.sub).replace("\n", "<br/>"), sub))
        return parts

    W = A4[0] - 32 * mm
    story: list = []
    for blk in layout(brief):
        if isinstance(blk, Cover):
            inner = [Paragraph(X(blk.kicker), S("k", 7.5, "white", fnt=bold)),
                     Spacer(1, 3),
                     Paragraph(X(blk.title), S("t", 22, "white", fnt=bold, leading=26)),
                     Spacer(1, 2),
                     Paragraph(X(blk.subtitle), S("st", 9, "white")),
                     Spacer(1, 8),
                     Paragraph(tag_markup(blk.status, 8.5), S("chip", 9, leading=13))]
            t = Table([[inner]], colWidths=[W])
            t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), col(C["rail"])),
                                   ("LEFTPADDING", (0, 0), (-1, -1), 16), ("RIGHTPADDING", (0, 0), (-1, -1), 16),
                                   ("TOPPADDING", (0, 0), (-1, -1), 16), ("BOTTOMPADDING", (0, 0), (-1, -1), 16)]))
            story += [t, Spacer(1, 6)]
        elif isinstance(blk, Stats):
            n = len(blk.items)
            cells = [[Paragraph(X(v), S("sv", 19, "ink", fnt=bold, leading=22)),
                      Paragraph(X(lbl.upper()), S("sl", 6.6, "muted", fnt=bold))] for v, lbl in blk.items]
            t = Table([cells], colWidths=[W / n] * n)
            t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), col(C["ground"])),
                                   ("LINEAFTER", (0, 0), (-2, -1), 3, colors.white),
                                   ("TOPPADDING", (0, 0), (-1, -1), 9), ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
                                   ("LEFTPADDING", (0, 0), (-1, -1), 10), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
            story += [t, Spacer(1, 4)]
        elif isinstance(blk, Heading):
            if blk.level == 1:
                hd = Table([[Paragraph(X(blk.text), h1)]], colWidths=[W])
                hd.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, -1), 1.4, col(C["rail"])),
                                        ("LEFTPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                                        ("TOPPADDING", (0, 0), (-1, -1), 6)]))
                group = [CondPageBreak(40 * mm), hd]
            else:
                group = [CondPageBreak(30 * mm), Paragraph(X(blk.text), h2)]
            if blk.lead:
                group.append(Paragraph(X(blk.lead), lead))
            else:
                group.append(Spacer(1, 4))
            story += group
        elif isinstance(blk, Callout):
            tone_line = C["rail"] if blk.tone == "rail" else C["talker"]
            inner = []
            if blk.body:
                inner.append(Paragraph(X(blk.body), S("cb", 10, "ink", leading=14.5)))
            for line in blk.bullets:
                inner.append(Paragraph(f'<font name="{bold}" color="#{C["rail"]}">•</font>&nbsp;&nbsp;{X(line)}',
                                       S("cbl", 9.5, "ink", leftIndent=10, firstLineIndent=-10, spaceBefore=2)))
            if blk.note:
                inner += [Spacer(1, 5), Paragraph(X(blk.note), S("cn", 7.2, "muted"))]
            t = Table([[inner]], colWidths=[W])
            t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), col(C["rail_soft"] if blk.tone == "rail" else C["talker_soft"])),
                                   ("LINEBEFORE", (0, 0), (0, -1), 3, col(tone_line)),
                                   ("LEFTPADDING", (0, 0), (-1, -1), 12), ("RIGHTPADDING", (0, 0), (-1, -1), 12),
                                   ("TOPPADDING", (0, 0), (-1, -1), 9), ("BOTTOMPADDING", (0, 0), (-1, -1), 9)]))
            story += [KeepTogether([t]), Spacer(1, 4)]
        elif isinstance(blk, Bullets):
            for t_, text in blk.items:
                prefix = (tag_markup(t_) + "&nbsp;&nbsp;") if t_ else ""
                story.append(Paragraph(prefix + X(text), S("bl", 9.5, "ink2", leading=13, spaceAfter=3)))
        elif isinstance(blk, TableBlock):
            data = [[Paragraph(X(h.upper()), head) for h in blk.headers]]
            data += [[cell_flow(v, blk.small) for v in row] for row in blk.rows]
            t = Table(data, colWidths=[W * w for w in blk.widths], repeatRows=1)
            t.setStyle(TableStyle([
                ("LINEBELOW", (0, 0), (-1, 0), 0.9, col(C["ink"])),
                ("LINEBELOW", (0, 1), (-1, -1), 0.35, col(C["line"])),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 4), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ("TOPPADDING", (0, 1), (-1, -1), 4.5), ("BOTTOMPADDING", (0, 1), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, 0), 4),
            ]))
            story += [t, Spacer(1, 5)]
        elif isinstance(blk, Note):
            story.append(Paragraph(X(blk.text), note))
            story.append(Spacer(1, 3))
        elif isinstance(blk, Break):
            story.append(PageBreak())

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont(font, 7)
        canvas.setFillColor(col(C["faint"]))
        canvas.drawString(16 * mm, 9 * mm, X(f"{brief.product}  ·  {FOOTER}").replace("&amp;", "&"))
        canvas.drawRightString(A4[0] - 16 * mm, 9 * mm, f"Page {doc.page}")
        canvas.restoreState()

    SimpleDocTemplate(str(path), pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=14 * mm,
                      bottomMargin=16 * mm, title=f"Design brief - {brief.product}", author="BriefForge"
                      ).build(story, onFirstPage=footer, onLaterPages=footer)
    return path
