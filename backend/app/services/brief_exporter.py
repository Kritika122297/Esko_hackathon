"""DOCX and PDF exports of the designer brief.

One layout feeds both formats, so Word and PDF always say the same thing:
  page 1   At a glance: status, counts, summary (AI-written when available), top priorities, waiting decisions
  then     1 What to do · 2 Approved copy and nutrition · 3 Open questions
  appendix For the record: decisions made, where each value came from, recent changes
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional, Tuple, Union

from app.services.designer import DesignerBrief, nutrition_format

# Colours from the app (tailwind.config): rail green, ground, ink, talker yellow, stop red.
C = {
    "rail": "0F3D2E", "rail_soft": "E3EDE8", "ground": "F1F2EC", "ink": "121514", "ink2": "2C322F",
    "muted": "5A615C", "faint": "757C77", "line": "D6D9CF", "white": "FFFFFF",
    "talker": "FFD23F", "talker_soft": "FFF4CC", "talker_deep": "8A6A00", "stop": "D92B2B", "stop_soft": "FBE8E6",
}
# tone -> (background, text)
TONES = {
    "change": ("121514", "FFFFFF"), "add": ("0F3D2E", "FFFFFF"), "remove": ("D92B2B", "FFFFFF"),
    "unknown": ("FFD23F", "121514"), "keep": ("F1F2EC", "2C322F"),
    "ok": ("0F3D2E", "FFFFFF"), "warn": ("FFD23F", "121514"), "stop": ("D92B2B", "FFFFFF"),
    "soft": ("F1F2EC", "2C322F"),
}
ACTION_WORD = {"change": "CHANGE", "add": "ADD", "remove": "REMOVE", "unknown": "PENDING", "keep": "KEEP"}
FOOTER = "Generated by BriefForge  ·  AI reads and suggests. Code checks. People decide."


# ---------------------------------------------------------------- layout


@dataclass
class Tag:
    text: str
    tone: str


@dataclass
class Cell:
    text: str
    sub: Optional[str] = None
    tag: Optional[Tag] = None
    bold: bool = False


CellLike = Union[str, Tag, Cell]


@dataclass
class Cover:
    kicker: str
    title: str
    subtitle: str
    status: Tag


@dataclass
class Stats:
    items: List[Tuple[str, str]]  # (value, label)


@dataclass
class Heading:
    text: str
    level: int = 1
    lead: Optional[str] = None


@dataclass
class Callout:
    body: str
    bullets: List[str] = field(default_factory=list)
    note: Optional[str] = None
    tone: str = "rail"  # rail: AI / summary box; warn: attention


@dataclass
class Bullets:
    items: List[Tuple[Optional[Tag], str]]


@dataclass
class TableBlock:
    headers: List[str]
    rows: List[List[CellLike]]
    widths: List[float]  # fractions of the text width
    small: bool = False


@dataclass
class Note:
    text: str


@dataclass
class Break:
    pass


Block = Union[Cover, Stats, Heading, Callout, Bullets, TableBlock, Note, Break]


_XML_ILLEGAL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f￾￿]")


def _xml_safe(text) -> str:
    """Word files cannot hold control characters (a vertical tab from an Excel cell, for example)."""
    return _XML_ILLEGAL.sub(" ", str(text or ""))


def _cut(text: Optional[str], n: int) -> str:
    """Shortens at a word boundary."""
    t = " ".join((text or "").split())
    if len(t) <= n:
        return t
    head = t[: n - 1]
    if " " in head[n // 2:]:
        head = head[: head.rfind(" ")]
    return head.rstrip(" ,;:-") + "…"


def _where(source: str) -> str:
    """'Content sheet B47 (note: ...): 'Calories: 166'' -> 'Content sheet B47'."""
    src = re.sub(r"\s*\(note:.*?\)(?=:|$)", "", source)
    return src.split(": ", 1)[0] if not src.startswith("Confirmed by reviewer") else "Confirmed by reviewer"


def _when(at: str) -> str:
    from datetime import datetime
    try:
        return datetime.fromisoformat(at.replace("Z", "+00:00")).strftime("%d %b %Y, %H:%M UTC")
    except ValueError:
        return at[:16].replace("T", " ")


def _panel(p: Optional[str]) -> str:
    return (p or "").replace("_", " ").strip().capitalize()


def _what(i) -> Tuple[str, Optional[str]]:
    """Instruction and the before/after detail for one design item."""
    if i.action == "change" and (i.current or i.new):
        return i.instruction, f"Now: {_cut(i.current, 110) or '—'}\nNew: {_cut(i.new, 110) or '—'}"
    if i.action == "add" and i.new:
        return i.instruction, _cut(i.new, 180)
    return i.instruction, None


def layout(b: DesignerBrief) -> List[Block]:
    r = b.readiness
    todo = [i for i in b.items if i.action != "keep"]
    keep = [i for i in b.items if i.action == "keep"]
    count = lambda a: sum(1 for i in b.items if i.action == a)  # noqa: E731
    waiting = [q for q in b.open_questions if q.status == "open"]

    if b.status == "finalized":
        status = Tag("FINAL  ·  ready for the agency", "ok")
    elif r and r.ready:
        status = Tag("DRAFT  ·  ready to finalize", "warn")
    else:
        status = Tag("DRAFT  ·  not ready for handoff", "stop")

    out: List[Block] = [
        Cover("PACKAGING DESIGN BRIEF", b.product,
              f"{(b.source_market + ' → ') if b.source_market else ''}{b.market} market  ·  {b.case}  ·  "
              f"Updated {_when(b.updated_at)}", status),
        Stats([(f"{r.score}%" if r else "–", "Readiness"), (str(count("change")), "To change"), (str(count("add")), "To add"),
               (str(count("remove")), "To remove"), (str(len(waiting)), "Decisions waiting")]),
        Heading("Summary"),
    ]
    if b.ai:
        out.append(Callout(b.ai.summary, note=f"Written by AI ({b.ai.model}) from the checked brief. Every figure in it was "
                                              "verified against the brief by code."))
    else:
        out.append(Callout(" ".join(b.summary + ([r.headline] if r else [])), tone="rail"))

    out.append(Heading("Top priorities", lead="What the designer needs to do first."))
    firsts = [i for i in todo if i.action in ("change", "add", "remove")] + [i for i in todo if i.action == "unknown"]
    if firsts:
        lines = []
        for i in firsts[:8]:
            text = f"{i.item}: {_cut(i.instruction, 110)}"
            if i.action == "change" and i.new:
                text = f"{i.item}: change to “{_cut(i.new, 90)}”"
            elif i.action == "unknown":
                reason = i.instruction.removeprefix("Waiting for a decision: ").split("; ")[0]
                text = f"{i.item}: waiting for a decision ({_cut(reason, 80)})"
            lines.append((Tag(ACTION_WORD.get(i.action, i.action.upper()), i.action), text))
        out.append(Bullets(lines))
        if len(firsts) > 8:
            out.append(Note(f"+ {len(firsts) - 8} more in section 1, What to do."))
    else:
        out.append(Note("No changes. Keep the current artwork."))

    out.append(Heading("Waiting on decisions"))
    if waiting:
        by_owner: dict = {}
        for q in waiting:
            by_owner.setdefault(q.owner, []).append(q.question)
        lines = []
        for owner, qs in by_owner.items():
            more = f"  (+{len(qs) - 3} more)" if len(qs) > 3 else ""
            lines.append((Tag(owner, "soft"), "; ".join(_cut(q, 80) for q in qs[:3]) + more))
        out.append(Bullets(lines))
    else:
        out.append(Note("Nothing is waiting. Every decision is made or passed to the agency."))

    if b.ai and b.ai.designer_notes:
        out.append(Heading("Notes for the designer"))
        out.append(Callout("", bullets=b.ai.designer_notes, note="Suggestions by AI, based on this brief."))

    # 1 What to do
    out.append(Heading("1   What to do", lead="Every item that changes on the pack, in order of action."))
    if todo:
        rows = []
        for i in todo:
            instr, detail = _what(i)
            rows.append([Tag(ACTION_WORD.get(i.action, i.action.upper()), i.action), Cell(i.item, sub=_panel(i.panel) or None, bold=True),
                         Cell(_cut(instr, 220), sub=detail)])
        out.append(TableBlock(["Action", "Item", "What to do"], rows, [0.14, 0.27, 0.59]))
    if keep:
        out.append(Note(f"Keep unchanged ({len(keep)}): " + ", ".join(i.item for i in keep) + "."))

    # 2 Approved copy
    out.append(Heading("2   Approved copy", lead="The text to set on the pack."))
    rows = []
    for c in b.final_copy:
        tag = None if c.status == "confirmed" else Tag("Missing" if c.status == "missing" else "Needs review",
                                                         "stop" if c.status == "missing" else "warn")
        rows.append([Cell(c.label, tag=tag, bold=True), Cell(_cut(c.value, 600) if c.value else "Not provided yet")])
    out.append(TableBlock(["Content", "Copy"], rows, [0.28, 0.72]))
    if any(n.get("amount") for n in b.nutrition):
        out.append(Heading("Nutrition Facts, per serving" if b.market.upper() == "US" else "Nutrition information",
                           level=2, lead=f"Lay out as: {nutrition_format(b.market)}."))
        unsure = False
        rows = []
        for n in b.nutrition:
            mark = "" if n.get("status") == "confirmed" else " *"
            unsure = unsure or bool(mark)
            rows.append([Cell(n["label"] + mark), n.get("amount") or "—", n.get("dv") or ""])
        out.append(TableBlock(["Nutrient", "Amount", "% Daily Value"], rows, [0.5, 0.25, 0.25], small=True))
        if unsure:
            out.append(Note("* Still needs review before print."))

    # 3 Open questions
    out.append(Heading("3   Open questions", lead="Decisions still to make, and items passed to the agency."))
    groups = [("Still to decide", [q for q in b.open_questions if q.status == "open"]),
              ("Passed to the agency or to check on the pack", [q for q in b.open_questions if q.status != "open"])]
    for title, qs in groups:
        if not qs:
            continue
        out.append(Heading(f"{title} ({len(qs)})", level=2))
        rows = []
        for q in sorted(qs, key=lambda q: q.owner):
            detail = q.detail.split(" — ", 1)[-1] if q.status == "agency" else q.detail
            rows.append([Cell(q.question, sub=_cut(detail, 120), bold=True), q.owner])
        out.append(TableBlock(["Question", "Owner"], rows, [0.82, 0.18]))
    if not b.open_questions:
        out.append(Note("None."))

    # Appendix
    out += [Break(), Heading("Appendix   For the record", lead="Decisions, sources and recent changes. The full history is kept in BriefForge.")]
    if b.decisions:
        out.append(Heading("Decisions made during review", level=2))
        out.append(TableBlock(["Question", "Answer", "By"],
                              [[_cut(d.question, 120), _cut(d.answer, 140), Cell(d.by, sub=_when(d.at))] for d in b.decisions],
                              [0.42, 0.38, 0.20], small=True))
    out.append(Heading("Where each value came from", level=2))
    rows = []
    for p in b.proof:
        places = list(dict.fromkeys(_where(x) for x in p.sources)) or ["No source"]
        more = f" (+{len(places) - 2})" if len(places) > 2 else ""
        rows.append([p.label, _cut(p.value, 70) or "—", ", ".join(places[:2]) + more])
    out.append(TableBlock(["Field", "Value", "Found in"], rows, [0.27, 0.38, 0.35], small=True))
    human = [c for c in b.change_log if c.by != "system"][-15:]
    if human:
        out.append(Heading("Recent changes", level=2))
        rows = []
        for c in reversed(human):
            what = " ".join(x for x in [c.field or c.issue or "",
                                        f"“{_cut(c.old, 40)}” → “{_cut(c.new, 40)}”" if c.new is not None and c.old else "",
                                        _cut(c.note, 120)] if x)
            rows.append([Cell(_when(c.at), sub=c.by), c.action.replace("_", " "), what or "—"])
        out.append(TableBlock(["When", "Action", "Detail"], rows, [0.24, 0.16, 0.60], small=True))
    return out


