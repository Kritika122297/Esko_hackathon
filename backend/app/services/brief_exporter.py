def export_docx(brief: DesignerBrief, path: Path) -> Path:
    import docx
    from docx.enum.table import WD_CELL_VERTICAL_ALIGNMENT
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Inches, Pt, RGBColor

    d = docx.Document()
    sec = d.sections[0]
    sec.left_margin = sec.right_margin = Inches(0.75)
    sec.top_margin = Inches(0.6)
    sec.bottom_margin = Inches(0.7)
    width = (sec.page_width - sec.left_margin - sec.right_margin) / 914400  # inches
    normal = d.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(10)
    normal.font.color.rgb = RGBColor.from_string(C["ink2"])
    normal.paragraph_format.space_after = Pt(0)

    def rgb(h):
        return RGBColor.from_string(h)

    def shd(parent, fill):
        el = OxmlElement("w:shd")
        el.set(qn("w:val"), "clear")
        el.set(qn("w:color"), "auto")
        el.set(qn("w:fill"), fill)
        parent.append(el)

    def borders(cell, **sides):
        tcPr = cell._tc.get_or_add_tcPr()
        el = OxmlElement("w:tcBorders")
        for side in ("top", "left", "bottom", "right"):
            b = OxmlElement(f"w:{side}")
            spec = sides.get(side)
            if spec:
                b.set(qn("w:val"), "single")
                b.set(qn("w:sz"), str(spec[0]))
                b.set(qn("w:color"), spec[1])
            else:
                b.set(qn("w:val"), "nil")
            el.append(b)
        tcPr.append(el)

    def fill(cell, colour):
        shd(cell._tc.get_or_add_tcPr(), colour)

    def pad(cell, top=60, bottom=60, left=100, right=100):
        tcPr = cell._tc.get_or_add_tcPr()
        mar = OxmlElement("w:tcMar")
        for side, v in (("top", top), ("left", left), ("bottom", bottom), ("right", right)):
            e = OxmlElement(f"w:{side}")
            e.set(qn("w:w"), str(v))
            e.set(qn("w:type"), "dxa")
            mar.append(e)
        tcPr.append(mar)

    def run(p, text, size=10, bold=False, colour=None, italic=False, bg=None):
        r = p.add_run(_xml_safe(text))
        r.font.size = Pt(size)
        r.font.bold = bold
        r.font.italic = italic
        if colour:
            r.font.color.rgb = rgb(colour)
        if bg:
            shd(r._r.get_or_add_rPr(), bg)
        return r

    def tag(p, t: Tag, size=7.5):
        bg, fg = TONES.get(t.tone, TONES["soft"])
        run(p, f" {t.text.upper()} ", size=size, bold=True, colour=fg, bg=bg)

    def spacing(p, before=0, after=0):
        p.paragraph_format.space_before = Pt(before)
        p.paragraph_format.space_after = Pt(after)

    def para(text="", size=10, colour=None, before=0, after=4, bold=False, italic=False):
        p = d.add_paragraph()
        spacing(p, before, after)
        if text:
            run(p, text, size=size, colour=colour, bold=bold, italic=italic)
        return p

    def grid(rows, cols, widths):
        t = d.add_table(rows=rows, cols=cols)
        t.autofit = False
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Inches(width * w)
        return t

    def cell_text(cell, value: CellLike, size):
        p = cell.paragraphs[0]
        if isinstance(value, Tag):
            tag(p, value)
            return
        c = value if isinstance(value, Cell) else Cell(str(value))
        run(p, c.text, size=size, bold=c.bold, colour=C["ink"] if c.bold else C["ink2"])
        if c.tag:
            run(p, "  ", size=size)
            tag(p, c.tag, size=6.5)
        if c.sub:
            for line in c.sub.split("\n"):
                sp = cell.add_paragraph()
                spacing(sp, 1, 0)
                run(sp, line, size=size - 1, colour=C["muted"])

    first_heading = True
    for blk in layout(brief):
        if isinstance(blk, Cover):
            t = grid(1, 1, [1.0])
            c = t.rows[0].cells[0]
            borders(c)
            fill(c, C["rail"])
            pad(c, 260, 260, 280, 280)
            p = c.paragraphs[0]
            run(p, blk.kicker, size=8, bold=True, colour="C9D8D1")
            p = c.add_paragraph()
            spacing(p, 4, 2)
            run(p, blk.title, size=22, bold=True, colour=C["white"])
            p = c.add_paragraph()
            spacing(p, 0, 10)
            run(p, blk.subtitle, size=9.5, colour="C9D8D1")
            p = c.add_paragraph()
            tag(p, blk.status, size=8.5)
            para(after=6)
        elif isinstance(blk, Stats):
            t = grid(1, len(blk.items), [1 / len(blk.items)] * len(blk.items))
            for cell, (value, label) in zip(t.rows[0].cells, blk.items):
                borders(cell, left=(18, C["white"]), right=(18, C["white"]))
                fill(cell, C["ground"])
                pad(cell, 120, 120, 140, 100)
                p = cell.paragraphs[0]
                run(p, value, size=20, bold=True, colour=C["ink"])
                p = cell.add_paragraph()
                run(p, label.upper(), size=7, bold=True, colour=C["muted"])
            para(after=2)
        elif isinstance(blk, Heading):
            if blk.level == 1:
                p = d.add_paragraph()
                pPr = p._p.get_or_add_pPr()
                bdr = OxmlElement("w:pBdr")
                bottom = OxmlElement("w:bottom")
                for k, v in (("val", "single"), ("sz", "12"), ("space", "3"), ("color", C["rail"])):
                    bottom.set(qn(f"w:{k}"), v)
                bdr.append(bottom)
                pPr.append(bdr)
                spacing(p, 6 if first_heading else 14, 4)
                p.paragraph_format.keep_with_next = True
                run(p, blk.text, size=14, bold=True, colour=C["ink"])
                first_heading = False
            else:
                p = para(blk.text, size=11, bold=True, colour=C["ink"], before=10, after=3)
                p.paragraph_format.keep_with_next = True
            if blk.lead:
                lp = para(blk.lead, size=9, colour=C["muted"], after=5)
                lp.paragraph_format.keep_with_next = True
        elif isinstance(blk, Callout):
            t = grid(1, 1, [1.0])
            c = t.rows[0].cells[0]
            borders(c, left=(36, C["rail"] if blk.tone == "rail" else C["talker"]))
            fill(c, C["rail_soft"] if blk.tone == "rail" else C["talker_soft"])
            pad(c, 140, 140, 220, 200)
            p = c.paragraphs[0]
            if blk.body:
                run(p, blk.body, size=10.5, colour=C["ink"])
            for i, line in enumerate(blk.bullets):
                bp = p if (i == 0 and not blk.body) else c.add_paragraph()
                spacing(bp, 2, 2)
                run(bp, "•  ", size=10, bold=True, colour=C["rail"])
                run(bp, line, size=10, colour=C["ink"])
            if blk.note:
                np_ = c.add_paragraph()
                spacing(np_, 6, 0)
                run(np_, blk.note, size=7.5, italic=True, colour=C["muted"])
            para(after=2)
        elif isinstance(blk, Bullets):
            for t_, text in blk.items:
                p = para(after=3)
                p.paragraph_format.left_indent = Inches(0.05)
                if t_:
                    tag(p, t_)
                    run(p, "  ", size=9)
                run(p, text, size=10, colour=C["ink2"])
        elif isinstance(blk, TableBlock):
            size = 8.5 if blk.small else 9.5
            t = grid(1 + len(blk.rows), len(blk.headers), blk.widths)
            for i, h in enumerate(blk.headers):
                cell = t.rows[0].cells[i]
                borders(cell, bottom=(10, C["ink"]))
                pad(cell, 40, 50)
                run(cell.paragraphs[0], h.upper(), size=7, bold=True, colour=C["muted"])
            hdr = t.rows[0]._tr.get_or_add_trPr()
            rep = OxmlElement("w:tblHeader")
            rep.set(qn("w:val"), "true")
            hdr.append(rep)
            for r_i, row in enumerate(blk.rows, start=1):
                for c_i, value in enumerate(row):
                    cell = t.rows[r_i].cells[c_i]
                    borders(cell, bottom=(4, C["line"]))
                    pad(cell, 70, 70)
                    cell_text(cell, value, size)
                    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.TOP
            para(after=4)
        elif isinstance(blk, Note):
            para(blk.text, size=9, colour=C["muted"], italic=True, before=2, after=4)
        elif isinstance(blk, Break):
            d.add_page_break()
            first_heading = True

    # Footer: product, line, page number
    footer_style = d.styles["Footer"]
    footer_style.font.size = Pt(7.5)  # the page-number field takes the style's size
    footer_style.font.color.rgb = rgb(C["faint"])
    fp = sec.footer.paragraphs[0]
    fp.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run(fp, f"{brief.product}  ·  {FOOTER}  ·  Page ", size=7.5, colour=C["faint"])
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), "PAGE")
    r = OxmlElement("w:r")
    rPr = OxmlElement("w:rPr")
    sz = OxmlElement("w:sz")
    sz.set(qn("w:val"), "15")
    rPr.append(sz)
    r.append(rPr)
    t = OxmlElement("w:t")
    t.text = "1"
    r.append(t)
    fld.append(r)
    fp._p.append(fld)

    d.core_properties.title = f"Design brief - {brief.product}"
    d.save(str(path))
    return path


